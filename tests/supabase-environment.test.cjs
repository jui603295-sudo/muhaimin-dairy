"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const html = fs.readFileSync(path.join(__dirname, "..", "index.html"), "utf8");
const configTemplate = fs.readFileSync(path.join(__dirname, "..", "src/core/supabase-test-config.example.js"), "utf8");
const guide = fs.readFileSync(path.join(__dirname, "..", "docs/TEST-SUPABASE-ENVIRONMENT.md"), "utf8");
const envIndex = html.indexOf('const MUHAIMIN_ENV = new URLSearchParams(window.location.search).get("env")');
const loaderIndex = html.indexOf('document.write(\'<script src="./src/core/supabase-test-config.js">');
const clientIndex = html.indexOf("const sb = supabase.createClient(SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY);");
assert.ok(envIndex >= 0, "environment selector must exist");
assert.ok(loaderIndex > envIndex, "local TEST config loader must follow the environment selector");
assert.ok(clientIndex > loaderIndex, "Supabase client creation must occur after TEST config validation");
assert.ok(html.includes('MUHAIMIN_ENV === "test" && (!MUHAIMIN_TEST_CONFIG'), "TEST mode must validate config");
assert.ok(html.includes('throw new Error("TEST environment blocked: valid local TEST Supabase config is required.")'), "invalid TEST config must stop startup");
assert.ok(html.includes('MUHAIMIN_ENV === "test" ? MUHAIMIN_TEST_CONFIG.url : "https://hhqshslzoznwyprhjzia.supabase.co"'), "Production fallback is permitted only in non-TEST mode");
assert.ok(configTemplate.includes("YOUR-TEST-PROJECT-REF"), "template must use a placeholder TEST URL");
assert.ok(configTemplate.includes("YOUR_TEST_ANON_OR_PUBLISHABLE_KEY"), "template must use a placeholder key");
assert.ok(!configTemplate.includes("hhqshslzoznwyprhjzia"), "template must not contain Production project ref");
assert.ok(guide.includes("must not fall back to Production"), "environment safety rule must be documented");
console.log("PASS: TEST Supabase config is isolated and fails closed when missing");
